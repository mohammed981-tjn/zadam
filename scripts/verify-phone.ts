import { toE164, toWesternDigits, COUNTRIES } from "../src/lib/phone";

let fail = 0;
const ok = (c: boolean, m: string) => {
  console.log(`  ${c ? "PASS" : "FAIL"}  ${m}`);
  if (!c) fail++;
};

const e164 = (dial: string, typed: string) => {
  const r = toE164(dial, typed);
  return r.ok ? r.e164 : null;
};

console.log("\nتحويل رقم الجوال إلى الصيغة الدولية\n");

console.log("الرقم السوداني كما يكتبه الناس:");
{
  ok(e164("249", "0912345678") === "249912345678", "الصفر البادئ يُحذف تلقائياً");
  ok(e164("249", "912345678") === "249912345678", "بدون صفر بادئ يعمل أيضاً");
  ok(e164("249", "0912 345 678") === "249912345678", "المسافات تُتجاهل");
  ok(e164("249", "0912-345-678") === "249912345678", "الشرطات تُتجاهل");
  ok(
    e164("249", "٠٩١٢٣٤٥٦٧٨") === "249912345678",
    "الأرقام العربية تُحوَّل — لوحة المفاتيح العربية شائعة",
  );
  ok(
    e164("249", "+249912345678") === "249912345678",
    "لصق الرقم الدولي كاملاً في خانة الرقم لا يكسر شيئاً",
  );
  ok(
    e164("249", "249912345678") === "249912345678",
    "تكرار مفتاح الدولة يُعالَج",
  );
}

console.log("\nالرفض حين يكون الرقم خاطئاً:");
{
  const short = toE164("249", "091234567");
  ok(!short.ok, "رقم ناقص رقماً يُرفض");
  ok(
    !short.ok && short.message.includes("السودان") && short.message.includes("9"),
    "رسالة الرفض تقول كم رقماً هو المطلوب وكم أدخل المستخدم",
  );

  ok(!toE164("249", "").ok, "الفراغ يُرفض");
  ok(!toE164("249", "abc").ok, "نص بلا أرقام يُرفض");
  ok(!toE164("999", "912345678").ok, "مفتاح دولة غير موجود يُرفض");
  ok(!toE164("249", "09123456789").ok, "رقم زائد يُرفض");
}

console.log("\nدول أخرى:");
{
  ok(e164("20", "01012345678") === "201012345678", "مصر: عشرة أرقام بعد المفتاح");
  ok(e164("966", "0512345678") === "966512345678", "السعودية: تسعة أرقام");
  ok(e164("971", "0501234567") === "971501234567", "الإمارات: تسعة أرقام");
  ok(e164("1", "4155551234") === "14155551234", "أمريكا: بلا صفر بادئ أصلاً");
}

console.log("\nسلامة القائمة:");
{
  ok(COUNTRIES[0].code === "SD", "السودان أول الخيارات");
  ok(
    new Set(COUNTRIES.map((c) => c.dial)).size === COUNTRIES.length,
    "لا يوجد مفتاح دولة مكرر",
  );
  ok(
    COUNTRIES.every((c) => /^\d+$/.test(c.dial)),
    "كل المفاتيح أرقام بلا علامة زائد",
  );
  ok(toWesternDigits("٠١٢٣٤٥٦٧٨٩") === "0123456789", "تحويل الأرقام العربية كاملاً");
  ok(toWesternDigits("۰۱۲۳") === "0123", "الأرقام الفارسية تُحوَّل كذلك");
}

console.log(`\n${fail === 0 ? "كل الفحوص نجحت" : `${fail} فحص فشل`}\n`);
process.exit(fail === 0 ? 0 : 1);
