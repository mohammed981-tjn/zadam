--
-- And it cited the FAOSTAT migration settling the same argument before it. Then
-- `/export` shipped and repeated the mistake: the whole export study lives in
-- `src/lib/exportTrade.ts`, a module the page imports. A visitor who opens the
-- page reads it. A visitor who *asks the assistant* — «ما شروط تصدير السمسم إلى
-- أوروبا؟» — gets nothing, because `knowledge_entries` has never heard of it.
--
-- Thirteen entries below close that. They are the study's substance, not links
-- to it: the assistant answers from `content`, so an entry that says «انظر
-- صفحة الصادر» answers nobody.
--
-- WHY THE PAGE STILL READS THE MODULE
--
-- Not moved, and the reason is worth stating rather than leaving as an
-- inconsistency. The page renders each figure with its source beside it through
-- `<Cite>`, and that binding of number-to-source is what the module's shape
-- exists for. These entries serve a different reader — one asking a question in
-- prose — and prose is what they hold.
--
-- WHICH LEAVES THE SAME FIGURE IN TWO PLACES, AND THAT IS A REAL RISK: the file
-- header of `exportTrade.ts` warns that a number written into a paragraph
-- drifts, and this migration writes numbers into paragraphs. So the drift is
-- caught mechanically rather than promised against: `scripts/verify-export-
-- knowledge.ts` reads both files and fails if any figure asserted here is
-- absent from the module. It needs no database — both sides are files in this
-- repository — so CI runs it on every push.
